void rom_propagate(rom_16x32_t *rom) {
    bit t01[32], t23[32], t45[32], t67[32], t89[32], tab[32], tcd[32], tef[32];
    bit t0123[32], t4567[32], t89ab[32], tcdef[32];
    bit t_lo[32], t_hi[32];

    mux2_32(rom->data[0], rom->data[1], rom->addr[0], t01);
    mux2_32(rom->data[2], rom->data[3], rom->addr[0], t23);
    mux2_32(rom->data[4], rom->data[5], rom->addr[0], t45);
    mux2_32(rom->data[6], rom->data[7], rom->addr[0], t67);
    mux2_32(rom->data[8], rom->data[9], rom->addr[0], t89);
    mux2_32(rom->data[10], rom->data[11], rom->addr[0], tab);
    mux2_32(rom->data[12], rom->data[13], rom->addr[0], tcd);
    mux2_32(rom->data[14], rom->data[15], rom->addr[0], tef);

    mux2_32(t01, t23, rom->addr[1], t0123);
    mux2_32(t45, t67, rom->addr[1], t4567);
    mux2_32(t89, tab, rom->addr[1], t89ab);
    mux2_32(tcd, tef, rom->addr[1], tcdef);

    mux2_32(t0123, t4567, rom->addr[2], t_lo);
    mux2_32(t89ab, tcdef, rom->addr[2], t_hi);

    mux2_32(t_lo, t_hi, rom->addr[3], rom->data_out);
}

