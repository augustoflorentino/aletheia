    bit c3[8] = {d->chars[3][0].q, d->chars[3][1].q, d->chars[3][2].q, d->chars[3][3].q, d->chars[3][4].q, d->chars[3][5].q, d->chars[3][6].q, d->chars[3][7].q};
    bit c4[8] = {d->chars[4][0].q, d->chars[4][1].q, d->chars[4][2].q, d->chars[4][3].q, d->chars[4][4].q, d->chars[4][5].q, d->chars[4][6].q, d->chars[4][7].q};
    bit c5[8] = {d->chars[5][0].q, d->chars[5][1].q, d->chars[5][2].q, d->chars[5][3].q, d->chars[5][4].q, d->chars[5][5].q, d->chars[5][6].q, d->chars[5][7].q};
    bit c6[8] = {d->chars[6][0].q, d->chars[6][1].q, d->chars[6][2].q, d->chars[6][3].q, d->chars[6][4].q, d->chars[6][5].q, d->chars[6][6].q, d->chars[6][7].q};
    bit c7[8] = {d->chars[7][0].q, d->chars[7][1].q, d->chars[7][2].q, d->chars[7][3].q, d->chars[7][4].q, d->chars[7][5].q, d->chars[7][6].q, d->chars[7][7].q};
